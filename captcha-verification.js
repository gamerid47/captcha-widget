/**
 * gCAPTCHA Verification - SECURE BACKEND VERSION
 * Works with Cloudflare Workers / any backend
 * No client-side markAsVerified() - all verification goes through backend
 */

class CaptchaVerification {
    constructor() {
        this.verifiedInstances = new Set();
        this.backendTokens = new Map();
        this.pendingChallenges = new Map();
        
        // Get backend URL from global config
        this.backendUrl = (window.gCaptchaConfig && window.gCaptchaConfig.backendUrl) || null;
this.requireBackend = (window.gCaptchaConfig && window.gCaptchaConfig.requireBackend) || false;
        
        // Warn if backend is required but not configured
        if (this.requireBackend && !this.backendUrl) {
            console.error('[gCAPTCHA] Backend required but no URL provided. Set window.gCaptchaConfig.backendUrl');
        }
        
        this.init();
    }

    init() {
        this.enableProtectedContent();
    }

    /**
     * Create a new CAPTCHA challenge (call before showing CAPTCHA)
     * @param {string} instanceId - The CAPTCHA instance ID
     * @param {string} type - captcha type (1,2,3)
     * @param {any} answer - The correct answer (generated by widget)
     * @param {any} challengeData - Data to send to frontend
     * @returns {Promise<string>} - challengeId
     */
    async createChallenge(instanceId, type, answer, challengeData) {
        if (!this.backendUrl) {
            console.error('[gCAPTCHA] No backend URL configured');
            return null;
        }
        
        try {
            const response = await fetch(`${this.backendUrl}/api/captcha/challenge`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    instanceId: instanceId,
                    type: type,
                    answer: answer,
                    challengeData: challengeData
                })
            });
            
            const result = await response.json();
            
            if (result.success) {
                this.pendingChallenges.set(instanceId, result.challengeId);
                return result.challengeId;
            }
            return null;
        } catch (error) {
            console.error('[gCAPTCHA] Failed to create challenge:', error);
            return null;
        }
    }

    /**
     * Verify CAPTCHA solution with backend
     * @param {string} instanceId - The CAPTCHA instance ID
     * @param {any} solution - The user's solution
     * @returns {Promise<boolean>} - True if verified
     */
    async verifyWithBackend(instanceId, solution) {
        if (!this.backendUrl) {
            console.error('[gCAPTCHA] No backend URL configured');
            return false;
        }
        
        const challengeId = this.pendingChallenges.get(instanceId);
        if (!challengeId) {
            console.error('[gCAPTCHA] No pending challenge for instance', instanceId);
            return false;
        }
        
        try {
            const response = await fetch(`${this.backendUrl}/api/captcha/verify`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({
                    instanceId: instanceId,
                    challengeId: challengeId,
                    solution: solution
                })
            });
            
            const result = await response.json();
            
            if (result.success) {
                this.markAsVerifiedSecure(instanceId, result.token);
                this.pendingChallenges.delete(instanceId);
                return true;
            } else {
                console.error('[gCAPTCHA] Verification failed:', result.error);
                return false;
            }
        } catch (error) {
            console.error('[gCAPTCHA] Backend verification error:', error);
            return false;
        }
    }

    /**
     * Internal method - marks instance as verified (only called after backend confirms)
     * @private
     */
    markAsVerifiedSecure(instanceId, backendToken) {
        this.verifiedInstances.add(instanceId);
        this.backendTokens.set(instanceId, backendToken);
        this.enableProtectedContent(instanceId);
        
        // Dispatch event for custom handlers
        document.dispatchEvent(new CustomEvent('captchaVerified', {
            detail: {
                instanceId: instanceId,
                backendToken: backendToken,
                timestamp: Date.now()
            }
        }));
    }

    /**
     * Check if an instance is verified
     */
    getVerificationStatus(instanceId = '1') {
        return this.verifiedInstances.has(instanceId);
    }

    /**
     * Get the backend token for an instance
     */
    getVerificationToken(instanceId = '1') {
        return this.backendTokens.get(instanceId);
    }

    /**
     * Reset verification for an instance
     */
    resetVerification(instanceId = null) {
        if (instanceId) {
            this.verifiedInstances.delete(instanceId);
            this.backendTokens.delete(instanceId);
            this.pendingChallenges.delete(instanceId);
            this.disableInstanceContent(instanceId);
        } else {
            this.verifiedInstances.clear();
            this.backendTokens.clear();
            this.pendingChallenges.clear();
            this.disableAllContent();
        }
    }

    enableProtectedContent(instanceId = null) {
        if (instanceId) {
            this.enableInstanceContent(instanceId);
        } else {
            this.verifiedInstances.forEach(instance => {
                this.enableInstanceContent(instance);
            });
        }
    }

    enableInstanceContent(instanceId) {
        // Handle buttons
        document.querySelectorAll(`.protected-btn-${instanceId}`).forEach(btn => {
            btn.disabled = false;
            btn.setAttribute('data-original-class', `protected-btn-${instanceId}`);
            btn.classList.remove(`protected-btn-${instanceId}`);
            btn.classList.add(`captcha-verified-${instanceId}`);
        });

        // Handle content
        document.querySelectorAll(`.protected-con-${instanceId}`).forEach(content => {
            content.setAttribute('data-was-protected-con', instanceId);
            content.classList.remove(`protected-con-${instanceId}`);
            content.classList.add(`captcha-verified-${instanceId}`);
            content.style.display = 'block';
        });

        // Handle content that lost its class
        document.querySelectorAll(`[data-was-protected-con="${instanceId}"]`).forEach(content => {
            if (!content.classList.contains(`captcha-verified-${instanceId}`)) {
                content.classList.remove(`protected-con-${instanceId}`);
                content.classList.add(`captcha-verified-${instanceId}`);
                content.style.display = 'block';
            }
        });

        // Handle indicators
        document.querySelectorAll(`.captcha-verified-indicator-${instanceId}`).forEach(indicator => {
            indicator.style.display = 'inline';
        });
    }

    disableInstanceContent(instanceId) {
        document.querySelectorAll(`.captcha-verified-${instanceId}`).forEach(element => {
            element.classList.remove(`captcha-verified-${instanceId}`);

            if (element.hasAttribute('data-original-class')) {
                element.classList.add(element.getAttribute('data-original-class'));
                element.removeAttribute('data-original-class');
            }

            if (element.tagName === 'BUTTON' || element.tagName === 'A' || element.tagName === 'INPUT') {
                element.disabled = true;
            }

            if (element.getAttribute('data-was-protected-con') === instanceId) {
                element.classList.add(`protected-con-${instanceId}`);
                element.removeAttribute('data-was-protected-con');
            }

            if (element.classList.contains(`protected-con-${instanceId}`)) {
                element.style.display = 'none';
            }

            if (element.classList.contains(`captcha-verified-indicator-${instanceId}`)) {
                element.style.display = 'none';
            }
        });

        document.querySelectorAll(`.protected-con-${instanceId}`).forEach(content => {
            content.style.display = 'none';
        });

        document.querySelectorAll(`[data-was-protected-con="${instanceId}"]`).forEach(content => {
            content.classList.add(`protected-con-${instanceId}`);
            content.style.display = 'none';
            content.removeAttribute('data-was-protected-con');
        });

        document.querySelectorAll(`.protected-btn-${instanceId}`).forEach(btn => {
            btn.disabled = true;
        });
    }

    disableAllContent() {
        document.querySelectorAll('[class*="protected-btn-"]').forEach(btn => {
            btn.disabled = true;
        });
        document.querySelectorAll('[class*="protected-con-"]').forEach(content => {
            content.style.display = 'none';
        });
        document.querySelectorAll('[class*="captcha-verified-indicator-"]').forEach(indicator => {
            indicator.style.display = 'none';
        });
    }

    getVerifiedInstances() {
        return Array.from(this.verifiedInstances);
    }

    isAnyVerified() {
        return this.verifiedInstances.size > 0;
    }

    removeInstance(instanceId) {
        this.verifiedInstances.delete(instanceId);
        this.backendTokens.delete(instanceId);
        this.pendingChallenges.delete(instanceId);
        this.disableInstanceContent(instanceId);
    }
}

// Create global instance
window.captchaVerification = new CaptchaVerification();